"""Seed the container's DSS server for testing dss-cluster-sched: users,
provider 'testprov' with three dummy services, saved sessions, and a scheduler
config at /home/dss/e2e/config.yaml. Runs as user dss from entrypoint.sh."""
import json
import os
import sys
import time

import httpx

sys.path.insert(0, '/opt/src/testing')
from dss_testenv import DSSTestServer, setup_environment  # noqa: E402

from itksnap_dss import DSSClient  # noqa: E402
from dss_cluster_sched.session import token_login, write_session  # noqa: E402

E2E = '/home/dss/e2e'
SERVICES = ('Dummy-AtlasA', 'Dummy-AtlasB', 'Dummy-Slow')

CONFIG = """\
# Generated by docker/bootstrap.py for the container's test cluster
instance: docker
executor: slurm
poll_interval: 5
claim_timeout: 30
state_dir: /home/dss/state
python: /opt/dss/bin/python

limits:
  max_jobs: 4
  max_queued: 2

servers:
  local:
    url: http://localhost:8080
    provider: testprov
    session_file: {e2e}/provider.session

jobs:
  dummy:
    scheduler:
      duration: "00:10:00"
      cpus: 1
    command: >-
      python /opt/src/testing/dummy_job.py --ticket {{ticket}}
      --atlas {{atlas}} --duration {{duration}} --fail {{fail}}
    defaults: {{atlas: none, duration: "5", fail: "no"}}
  dummy_slow:
    scheduler:
      duration: "00:10:00"
      cpus: 1
    command: python /opt/src/testing/dummy_job.py --ticket {{ticket}} --duration 20
    limits: {{max_jobs: 1}}

services:
  atlas-a:
    name: Dummy-AtlasA
    job: dummy
    params: {{atlas: /atlases/A}}
  atlas-b:
    name: Dummy-AtlasB
    job: dummy
    params: {{atlas: /atlases/B}}
    limits: {{max_jobs: 2}}
  slow:
    name: Dummy-Slow
    job: dummy_slow
"""


def main():
    if os.path.exists(os.path.join(E2E, 'info.json')):
        print('bootstrap: already done')
        return
    server = DSSTestServer('/home/dss/dss-server', port=8080)
    deadline = time.time() + 30
    while True:
        try:
            httpx.get(server.base_url + '/about', timeout=1)
            break
        except httpx.TransportError:
            if time.time() > deadline:
                raise
            time.sleep(0.5)

    env = setup_environment(server, services=SERVICES)
    os.makedirs(E2E, exist_ok=True)
    write_session(os.path.join(E2E, 'provider.session'),
                  token_login(DSSClient(server.base_url), env['tokens']['provider']))
    write_session(os.path.join(E2E, 'consumer.session'),
                  env['consumer'].cookies['webpy_session_id'])
    with open(os.path.join(E2E, 'config.yaml'), 'w') as f:
        f.write(CONFIG.format(e2e=E2E))
    with open(os.path.join(E2E, 'info.json'), 'w') as f:
        json.dump({'url': server.base_url, 'sqlite': server.sqlite_path,
                   'githashes': env['githashes'], 'provider': env['provider']}, f, indent=1)
    print('bootstrap: DSS server ready at %s with services %s' % (server.base_url, ', '.join(SERVICES)))
    print('bootstrap: scheduler config at %s/config.yaml' % E2E)


if __name__ == '__main__':
    main()
